/**
 * Generate the Rust language tables from the two pinned inputs they come from.
 *
 * Usage: deno run --allow-read --allow-write scripts/generate-language-tables.ts <UnicodeData.txt> <entities.json>
 *
 * The word-character ranges come from Unicode 15.1.0 `UnicodeData.txt`
 * (https://www.unicode.org/Public/15.1.0/ucd/UnicodeData.txt). The entity table
 * comes from the WHATWG `entities.json`. Both inputs are pinned by digest, and
 * the output is checked in; run this only to change a pin.
 */

const UNICODE_SHA256 =
  "2fc713e6a31a87c4850a37fe2caffa4218180fadb5de86b43a143ddb4581fb86";
const ENTITIES_SHA256 =
  "d741d877ac77c4194c4ad526b5b4a19aef8dfe411ab840a466891cdbb9f362e6";
const outputDir = new URL(
  "../packages/core/rust/language/data/",
  import.meta.url,
);

const [unicodePath, entitiesPath] = Deno.args;
if (!unicodePath || !entitiesPath) {
  throw new Error(
    "Pass the paths to UnicodeData.txt and the WHATWG entities.json",
  );
}

async function readPinned(
  path: string,
  expected: string,
  label: string,
): Promise<Uint8Array> {
  const bytes = await Deno.readFile(path);
  const digest = [
    ...new Uint8Array(await crypto.subtle.digest("SHA-256", bytes)),
  ].map((n) => n.toString(16).padStart(2, "0")).join("");
  if (digest !== expected) {
    throw new Error(`Unexpected ${label} digest ${digest}`);
  }
  return bytes;
}

const hex = (n: number) => `0x${n.toString(16)}`;

const ranges: [number, number][] = [];
let first: number | undefined;
const unicode = new TextDecoder().decode(
  await readPinned(unicodePath, UNICODE_SHA256, "UnicodeData.txt"),
);
for (const row of unicode.split("\n")) {
  if (!row) continue;
  const [code, name, category] = row.split(";");
  const point = parseInt(code, 16);
  if (name.endsWith(", First>")) {
    first = point;
    continue;
  }
  const start = name.endsWith(", Last>") ? first! : point;
  if (
    /^[LMN]/.test(category) || category === "Pc" || point === 0x200c ||
    point === 0x200d
  ) {
    const previous = ranges.at(-1);
    if (previous && previous[1] + 1 === start) previous[1] = point;
    else ranges.push([start, point]);
  }
}
const words = `// Generated by scripts/generate-language-tables.ts. Do not edit.
// Unicode 15.1.0 L/M/N/Pc plus U+200C/U+200D (UnicodeData.txt, SHA-256 ${UNICODE_SHA256}).
pub const WORD_CHARACTER_RANGES: &[(u32, u32)] = &[
${ranges.map(([a, b]) => `    (${hex(a)}, ${hex(b)}),`).join("\n")}
];
`;

const entities = JSON.parse(
  new TextDecoder().decode(
    await readPinned(entitiesPath, ENTITIES_SHA256, "entities.json"),
  ),
) as Record<string, { characters: string }>;
const names = Object.keys(entities).sort();
const rustString = (text: string) =>
  `"${
    [...text].map((c) => `\\u{${c.codePointAt(0)!.toString(16)}}`).join("")
  }"`;
const html = `// Generated by scripts/generate-language-tables.ts. Do not edit.
// WHATWG HTML named character references (entities.json, SHA-256 ${ENTITIES_SHA256}).
// Names are stored without the leading '&', sorted for binary search; legacy names without ';' are included.
pub const HTML_ENTITIES: &[(&str, &str)] = &[
${
  names.map((n) =>
    `    ("${n.slice(1)}", ${rustString(entities[n].characters)}),`
  ).join("\n")
}
];
`;

await Deno.mkdir(outputDir, { recursive: true });
await Deno.writeTextFile(new URL("word_characters.rs", outputDir), words);
await Deno.writeTextFile(new URL("html_entities.rs", outputDir), html);
